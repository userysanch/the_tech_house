-- The Tech House - POS e Inventario
-- SQL Server (SQLEXPRESS)

IF DB_ID('TheTechHouse') IS NULL
    CREATE DATABASE TheTechHouse;
GO
USE TheTechHouse;
GO

CREATE TABLE ROLES (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    NOMBRE VARCHAR(30) NOT NULL,
    DESCRIPCION VARCHAR(150) NOT NULL DEFAULT ''
);

CREATE TABLE CATEGORIAS (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    NOMBRE VARCHAR(80) NOT NULL,
    DESCRIPCION VARCHAR(200) NOT NULL DEFAULT ''
);

CREATE TABLE MARCAS (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    NOMBRE VARCHAR(80) NOT NULL
);

CREATE TABLE PROVEEDORES (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    NOMBRE VARCHAR(150) NOT NULL,
    NIT VARCHAR(30) NULL,
    TELEFONO VARCHAR(30) NULL,
    EMAIL VARCHAR(100) NULL,
    DIRECCION VARCHAR(200) NULL
);

CREATE TABLE CLIENTES (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    NOMBRE VARCHAR(150) NOT NULL,
    NIT VARCHAR(30) NULL,
    TELEFONO VARCHAR(30) NULL,
    EMAIL VARCHAR(100) NULL,
    DIRECCION VARCHAR(200) NULL
);

CREATE TABLE FORMAS_PAGO (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    NOMBRE VARCHAR(50) NOT NULL
);

CREATE TABLE USUARIOS (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    USERNAME VARCHAR(80) NOT NULL,
    PASSWORD_HASH VARCHAR(255) NOT NULL,
    NOMBRE VARCHAR(150) NOT NULL,
    ROL VARCHAR(20) NOT NULL DEFAULT 'empleado',
    ROL_ID INT NULL,
    CONSTRAINT FK_USUARIOS_ROL FOREIGN KEY (ROL_ID) REFERENCES ROLES(ID)
);

CREATE TABLE PRODUCTOS (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    CODIGO VARCHAR(50) NOT NULL,
    NOMBRE VARCHAR(150) NOT NULL,
    COSTO DECIMAL(10,2) NOT NULL DEFAULT 0,
    MARGEN DECIMAL(5,2) NOT NULL DEFAULT 0,
    PRECIO DECIMAL(10,2) NOT NULL DEFAULT 0,
    STOCK INT NOT NULL DEFAULT 0,
    CODIGO_BARRAS VARCHAR(50) NULL,
    CATEGORIA_ID INT NULL,
    MARCA_ID INT NULL,
    PROVEEDOR_ID INT NULL,
    CONSTRAINT UQ_PRODUCTOS_CODIGO UNIQUE (CODIGO),
    CONSTRAINT FK_PRODUCTOS_CATEGORIA FOREIGN KEY (CATEGORIA_ID) REFERENCES CATEGORIAS(ID),
    CONSTRAINT FK_PRODUCTOS_MARCA FOREIGN KEY (MARCA_ID) REFERENCES MARCAS(ID),
    CONSTRAINT FK_PRODUCTOS_PROVEEDOR FOREIGN KEY (PROVEEDOR_ID) REFERENCES PROVEEDORES(ID)
);

CREATE TABLE ENTRADAS (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    FECHA DATETIME NOT NULL DEFAULT GETDATE(),
    CODIGO_PRODUCTO VARCHAR(50) NOT NULL,
    CANTIDAD INT NOT NULL,
    COSTO_UNITARIO DECIMAL(10,2) NOT NULL,
    UPC VARCHAR(50) NULL,
    PROVEEDOR_ID INT NULL,
    CONSTRAINT FK_ENTRADAS_PRODUCTO FOREIGN KEY (CODIGO_PRODUCTO) REFERENCES PRODUCTOS(CODIGO),
    CONSTRAINT FK_ENTRADAS_PROVEEDOR FOREIGN KEY (PROVEEDOR_ID) REFERENCES PROVEEDORES(ID)
);

CREATE TABLE MOVIMIENTOS_INVENTARIO (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    CODIGO_PRODUCTO VARCHAR(50) NOT NULL,
    TIPO VARCHAR(20) NOT NULL,
    CANTIDAD INT NOT NULL,
    FECHA DATETIME NOT NULL DEFAULT GETDATE(),
    REFERENCIA VARCHAR(150) NOT NULL DEFAULT '',
    CONSTRAINT FK_MOVIMIENTOS_PRODUCTO FOREIGN KEY (CODIGO_PRODUCTO) REFERENCES PRODUCTOS(CODIGO),
    CONSTRAINT CK_TIPO_MOVIMIENTO CHECK (TIPO IN ('entrada', 'salida', 'ajuste', 'devolucion'))
);

CREATE TABLE PROMOCIONES (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    CODIGO_PRODUCTO VARCHAR(50) NOT NULL,
    DESCRIPCION VARCHAR(150) NOT NULL,
    PORCENTAJE DECIMAL(5,2) NOT NULL DEFAULT 0,
    FECHA_INICIO DATETIME NOT NULL,
    FECHA_FIN DATETIME NOT NULL,
    ACTIVA BIT NOT NULL DEFAULT 1,
    CONSTRAINT FK_PROMOCIONES_PRODUCTO FOREIGN KEY (CODIGO_PRODUCTO) REFERENCES PRODUCTOS(CODIGO)
);

CREATE TABLE VENTAS (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    FECHA DATETIME NOT NULL DEFAULT GETDATE(),
    TOTAL_VENTA DECIMAL(10,2) NOT NULL DEFAULT 0,
    GANANCIA_TOTAL DECIMAL(10,2) NOT NULL DEFAULT 0,
    CLIENTE_ID INT NULL,
    CONSTRAINT FK_VENTAS_CLIENTE FOREIGN KEY (CLIENTE_ID) REFERENCES CLIENTES(ID)
);

CREATE TABLE DETALLE_VENTAS (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    VENTA_ID INT NOT NULL,
    CODIGO_PRODUCTO VARCHAR(50) NOT NULL,
    CANTIDAD INT NOT NULL,
    PRECIO_UNITARIO DECIMAL(10,2) NOT NULL,
    TOTAL DECIMAL(10,2) NOT NULL,
    GANANCIA DECIMAL(10,2) NOT NULL DEFAULT 0,
    CONSTRAINT FK_DETALLE_VENTA FOREIGN KEY (VENTA_ID) REFERENCES VENTAS(ID),
    CONSTRAINT FK_DETALLE_PRODUCTO FOREIGN KEY (CODIGO_PRODUCTO) REFERENCES PRODUCTOS(CODIGO),
    CONSTRAINT CK_CANTIDAD_POSITIVA CHECK (CANTIDAD > 0)
);

CREATE TABLE PAGOS_VENTA (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    VENTA_ID INT NOT NULL,
    FORMA_PAGO_ID INT NOT NULL,
    MONTO DECIMAL(10,2) NOT NULL,
    FECHA DATETIME NOT NULL DEFAULT GETDATE(),
    CONSTRAINT FK_PAGOS_VENTA FOREIGN KEY (VENTA_ID) REFERENCES VENTAS(ID),
    CONSTRAINT FK_PAGOS_FORMA FOREIGN KEY (FORMA_PAGO_ID) REFERENCES FORMAS_PAGO(ID)
);

CREATE TABLE DEVOLUCIONES (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    VENTA_ID INT NOT NULL,
    FECHA DATETIME NOT NULL DEFAULT GETDATE(),
    MOTIVO VARCHAR(200) NOT NULL DEFAULT '',
    MONTO_TOTAL DECIMAL(10,2) NOT NULL DEFAULT 0,
    CONSTRAINT FK_DEVOLUCIONES_VENTA FOREIGN KEY (VENTA_ID) REFERENCES VENTAS(ID)
);

CREATE TABLE DETALLE_DEVOLUCIONES (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    DEVOLUCION_ID INT NOT NULL,
    CODIGO_PRODUCTO VARCHAR(50) NOT NULL,
    CANTIDAD INT NOT NULL,
    SUBTOTAL DECIMAL(10,2) NOT NULL DEFAULT 0,
    CONSTRAINT FK_DDEVOLUCION_DEV FOREIGN KEY (DEVOLUCION_ID) REFERENCES DEVOLUCIONES(ID),
    CONSTRAINT FK_DDEVOLUCION_PRODUCTO FOREIGN KEY (CODIGO_PRODUCTO) REFERENCES PRODUCTOS(CODIGO)
);

CREATE TABLE VENTAS_PENDIENTES (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    SCANNER_CODE VARCHAR(50) NOT NULL,
    PRODUCTO_CODIGO VARCHAR(50) NOT NULL,
    PRODUCTO_NOMBRE VARCHAR(150) NOT NULL,
    CANTIDAD INT NOT NULL DEFAULT 1,
    PRECIO_UNITARIO DECIMAL(10,2) NOT NULL,
    TOTAL DECIMAL(10,2) NOT NULL,
    CELULAR_IP VARCHAR(50) NULL,
    FECHA DATETIME NOT NULL DEFAULT GETDATE(),
    ESTADO VARCHAR(20) NOT NULL DEFAULT 'pendiente'
);

CREATE TABLE CAJAS (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    NOMBRE VARCHAR(60) NOT NULL,
    UBICACION VARCHAR(120) NOT NULL DEFAULT ''
);

CREATE TABLE TURNOS_CAJA (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    CAJA_ID INT NOT NULL,
    USUARIO_ID INT NOT NULL,
    FECHA_APERTURA DATETIME NOT NULL DEFAULT GETDATE(),
    FECHA_CIERRE DATETIME NULL,
    SALDO_INICIAL DECIMAL(10,2) NOT NULL DEFAULT 0,
    SALDO_FINAL DECIMAL(10,2) NULL,
    ESTADO VARCHAR(20) NOT NULL DEFAULT 'abierto',
    CONSTRAINT FK_TURNOS_CAJA FOREIGN KEY (CAJA_ID) REFERENCES CAJAS(ID),
    CONSTRAINT FK_TURNOS_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIOS(ID),
    CONSTRAINT CK_ESTADO_TURNO CHECK (ESTADO IN ('abierto', 'cerrado'))
);

CREATE TABLE MOVIMIENTOS_CAJA (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    TURNO_ID INT NOT NULL,
    TIPO VARCHAR(20) NOT NULL,
    MONTO DECIMAL(10,2) NOT NULL,
    DESCRIPCION VARCHAR(150) NOT NULL DEFAULT '',
    FECHA DATETIME NOT NULL DEFAULT GETDATE(),
    CONSTRAINT FK_MOVIMIENTOS_TURNO FOREIGN KEY (TURNO_ID) REFERENCES TURNOS_CAJA(ID),
    CONSTRAINT CK_TIPO_MOVIMIENTO_CAJA CHECK (TIPO IN ('ingreso', 'egreso', 'venta'))
);
GO

